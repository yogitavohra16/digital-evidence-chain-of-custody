"""models.py - the database tables for cases, evidence and custody events.

WHAT IS A DJANGO MODEL?
    A model is a Python class that describes ONE database table. Each attribute
    (CharField, DateTimeField, ForeignKey ...) is one column. Django's ORM lets us
    read and write rows using Python objects instead of writing SQL by hand.

WHAT IS A MIGRATION?
    Changing a model does not change the database by itself. Running
        python manage.py makemigrations   -> writes a migration file (the plan)
        python manage.py migrate          -> applies the plan to db.sqlite3
    keeps the database tables in step with the models. Ready-made migrations are
    already included in this project, so you normally only need `migrate`.
"""
import uuid
from pathlib import Path

from django.conf import settings
from django.db import models
from django.utils import timezone

from .storage import PrivateEvidenceStorage


class Case(models.Model):
    """An investigation case. Evidence items are grouped under a case."""

    class Status(models.TextChoices):
        OPEN = "OPEN", "Open"
        UNDER_REVIEW = "UNDER_REVIEW", "Under review"
        CLOSED = "CLOSED", "Closed"

    # case_id is a human-friendly unique code such as CASE-0001 (generated by us).
    case_id = models.CharField(max_length=20, unique=True)
    title = models.CharField(max_length=200)
    description = models.TextField(blank=True)
    status = models.CharField(max_length=20, choices=Status.choices, default=Status.OPEN)
    # PROTECT: a user who created cases cannot be deleted while those cases exist.
    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="cases_created"
    )
    created_at = models.DateTimeField(default=timezone.now)

    class Meta:
        ordering = ["-created_at", "-id"]

    def __str__(self):
        return f"{self.case_id} - {self.title}"


def evidence_upload_path(instance, filename):
    """Choose a SAFE storage path for an uploaded evidence file.

    Why: we never use the user's filename as the path. A name such as
    '../../settings.py' could try to escape the evidence folder (path traversal),
    and two uploads with the same name would overwrite each other. Instead we create
    a random UUID name and keep only a cleaned-up, lower-case file extension.
    The original filename is saved separately in the database for display.
    """
    extension = Path(filename).suffix.lower()
    return f"evidence_files/{uuid.uuid4().hex}{extension}"


class Evidence(models.Model):
    """One registered digital evidence item (metadata + reference to the file)."""

    class Status(models.TextChoices):
        REGISTERED = "REGISTERED", "Registered"
        TRANSFERRED = "TRANSFERRED", "Transferred"
        IN_ANALYSIS = "IN_ANALYSIS", "In analysis"
        ANALYSIS_COMPLETED = "ANALYSIS_COMPLETED", "Analysis completed"
        RETURNED = "RETURNED", "Returned"
        ARCHIVED = "ARCHIVED", "Archived"

    # Unique identifier such as EV-0001. unique=True makes the DATABASE refuse duplicates.
    evidence_id = models.CharField(max_length=20, unique=True)
    # PROTECT: a case with evidence cannot be deleted (prevents inconsistent references).
    case = models.ForeignKey(Case, on_delete=models.PROTECT, related_name="evidence_items")
    original_filename = models.CharField(max_length=255)
    file_extension = models.CharField(max_length=20)
    file_size = models.PositiveBigIntegerField(help_text="Size in bytes")
    # The file itself lives in the private folder; the database only stores its path.
    stored_file = models.FileField(upload_to=evidence_upload_path, storage=PrivateEvidenceStorage(), max_length=255)
    # The ORIGINAL SHA-256 hash. It is written once at registration and never updated
    # by verification (a mismatch must never silently replace the original value).
    sha256_hash = models.CharField(max_length=64)
    registered_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="evidence_registered"
    )
    registered_at = models.DateTimeField(default=timezone.now)
    notes = models.TextField(blank=True)
    status = models.CharField(max_length=30, choices=Status.choices, default=Status.REGISTERED)

    class Meta:
        ordering = ["-registered_at", "-id"]
        constraints = [
            # The hash must look like a SHA-256 hex digest: exactly 64 characters.
            models.CheckConstraint(
                condition=models.Q(sha256_hash__regex=r"^[0-9a-f]{64}$"),
                name="evidence_sha256_is_64_hex_chars",
            ),
        ]

    def __str__(self):
        return f"{self.evidence_id} ({self.original_filename})"


class CustodyEvent(models.Model):
    """One entry in an evidence item's chain of custody.

    Append-oriented: the application provides NO page to edit or delete these rows,
    and the admin site shows them read-only. Each event is also written to the
    blockchain (see blockchain.models.BlockRecord, linked by a one-to-one field).
    """

    class ActionType(models.TextChoices):
        REGISTERED = "REGISTERED", "Evidence collected / registered"
        TRANSFERRED = "TRANSFERRED", "Evidence transferred"
        ACCESSED = "ACCESSED", "Evidence accessed"
        ANALYSIS_STARTED = "ANALYSIS_STARTED", "Analysis started"
        ANALYSIS_COMPLETED = "ANALYSIS_COMPLETED", "Analysis completed"
        RETURNED = "RETURNED", "Evidence returned"
        ARCHIVED = "ARCHIVED", "Evidence archived"

    evidence = models.ForeignKey(Evidence, on_delete=models.PROTECT, related_name="custody_events")
    action_type = models.CharField(max_length=30, choices=ActionType.choices)
    # The logged-in account that recorded the event (Django authentication).
    recorded_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.PROTECT, related_name="custody_events_recorded"
    )
    # The person who physically handled the evidence, typed in by the user. A
    # username alone does NOT prove the real-world identity of the handler.
    handler_name = models.CharField(max_length=120)
    # The timestamp is set by the SERVER (not typed by the user) so it cannot be back-dated.
    timestamp = models.DateTimeField(default=timezone.now)
    from_party = models.CharField(max_length=120, blank=True)
    to_party = models.CharField(max_length=120, blank=True)
    remarks = models.TextField(blank=True)
    # A COPY of the evidence's original SHA-256 hash at the time of the event.
    evidence_hash = models.CharField(max_length=64)

    class Meta:
        ordering = ["timestamp", "id"]   # chronological order, oldest first

    def __str__(self):
        return f"{self.evidence.evidence_id} - {self.get_action_type_display()}"
